// Regenerates src/game/audio/soundFiles.ts from public/sounds (audio--001 step 1). Run after adding/removing sounds.
import { readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..', '..')
const list = (dir) => readdirSync(join(root, 'public/sounds', dir), { withFileTypes: true }).filter((d) => d.isFile() && /\.(ogg|mp3)$/.test(d.name)).map((d) => (dir ? `${dir}/${d.name}` : d.name)).sort()
const files = [...list(''), ...list('voices')]
const body = `/** Generated by scripts/assets/sound-catalogue.mjs from public/sounds — do not edit by hand. */\nexport const SOUND_FILES: readonly string[] = ${JSON.stringify(files, null, 2)}\n`
writeFileSync(join(root, 'src/game/audio/soundFiles.ts'), body)
console.log(`sound-catalogue: ${files.length} files`)
